let lang = 'es';

export const normalizeLang = (l) => (LANGS.includes(l) ? l : 'es');
export function setLang(l) { lang = normalizeLang(l); return lang; }
export const getLang = () => lang;
export const locale = () => LOCALES[lang];

// Texto de la clave en el idioma actual, con {variables} sustituidas. Si falta, cae al español y luego a la clave.
export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.es[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

// Números con el formato del idioma actual: horas con hasta 2 decimales y porcentajes con 1 decimal.
export const fmtNum = (x) => new Intl.NumberFormat(locale(), { maximumFractionDigits: 2 }).format(x);
export const fmtPct = (p, minDecimales = 1) => new Intl.NumberFormat(locale(), { style: 'percent', minimumFractionDigits: minDecimales, maximumFractionDigits: 1 }).format(p / 100);
export const fmtDate = (iso, opts) => new Intl.DateTimeFormat(locale(), { timeZone: 'UTC', ...opts }).format(new Date(iso + 'T00:00:00Z'));

// Etiqueta de la fecha de fin que da FaltasWeb.niveles (en español) -> clave.
export const corteKey = (label) => (/FCT/.test(label) ? 'corte.fct' : 'corte.curso');
